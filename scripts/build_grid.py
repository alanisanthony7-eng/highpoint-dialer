"""Build exact quoter prices from the Insurance Toolkits grid (data/toolkits-grid.jsonl) into public/hp-grid.js.
The grid is every age 40-89 x sex x nicotine x face $5,000-$100,000 (step $5,000), clean health, bank draft, quoted live on Insurance Toolkits.
A carrier plan only answers for the faces it sells at that age, so each age keeps the prices at the faces it returned.
Premium between two quoted faces is linear (checked: within a cent), so the quoter interpolates. Nothing above the highest quoted face is priced.
Usage: python3 -I scripts/build_grid.py"""
import json, re, collections
FACES = [5000, 10000, 15000, 20000, 25000, 30000]
# Toolkits (company, plan) -> grid product id. Each product id is what hp-grid.js stores and desk-app.js asks for.
MAP = {
 ("CVS (Aetna Accendo)", "Accendo Preferred"): "accendo.pref",
 ("CVS (Aetna Accendo)", "Accendo Standard"): "accendo.std",
 ("Aetna (Protection Series)", "Protection Series Preferred"): "aetna.pref",
 ("American Home Life (Patriot Series)", "Patriot Series Preferred"): "ahl.pref",
 ("American Home Life (Patriot Series)", "Patriot Series Standard"): "ahl.std",
 ("American Home Life (GuideStar 45+)", "GuideStar Level"): "ahl.gs",
 ("American Home Life (GuideStar 0-44)", "GuideStar Level"): "ahl.gs",
 ("Foresters (PlanRight)", "PlanRight Preferred"): "for.pref",
 ("Foresters (PlanRight)", "PlanRight Standard"): "for.std",
 ("AIG (SIWL)", "SimpliNow Legacy Max"): "aig.siwl",
 ("AIG (GIWL)", "Guaranteed Issue"): "aig.gi",
 ("Fidelity (RAPIDecision Final Expense)", "Level"): "fid.level",
 ("TruStage (Whole Life - Final Expense - Level)", "Whole Life / Final Expense - Level"): "tru.level",
 ("TruStage (Whole Life - Final Expense - Guaranteed)", "Whole Life / Final Expense - Guaranteed"): "tru.gi",
}
look = lambda s: bool(re.fullmatch(r"[A-Za-z0-9]{20,}", s or ""))  # the scrape sometimes returns an id where a name should be
ser = collections.defaultdict(dict)  # (product, sex+nic, age) -> {face: monthly}
for line in open("data/toolkits-grid.jsonl"):
    r = json.loads(line)
    if r.get("health") not in (None, "clean"): continue
    k = ("M" if r["sex"] == "Male" else "F") + ("1" if r["tobacco"] != "None" else "0")
    for c, p, m, t in r["q"]:
        if look(c) or look(p) or m is None: continue
        pid = MAP.get((c, p))
        if pid and r["face"] in FACES: ser[(pid, k, r["age"])][r["face"]] = m
prods = {}
for (pid, k, age), d in ser.items():
    P = prods.setdefault(pid, {})
    P.setdefault(k, {})[age] = [d.get(f) for f in FACES]
out = {}
for pid, P in sorted(prods.items()):
    ages = sorted({a for k in P for a in P[k]})
    a0, a1 = ages[0], ages[-1]
    out[pid] = {"ages": [a0, a1], **{k: [P[k].get(a) for a in range(a0, a1 + 1)] for k in sorted(P)}}
js = """/* Generated by scripts/build_grid.py from data/toolkits-grid.jsonl. Do not edit by hand.
   Real monthly bank-draft prices from Insurance Toolkits, clean health, for every age, sex and nicotine answer, at each face the plan sells. */
(() => {
  const G = %s;
  const FACES = G.faces;
  // monthly price for one product, or null when the plan isn't sold at this age / face. o = { age, sex: "M"|"F", tob, face }
  function price(id, o) {
    const P = G.products[id]; if (!P) return null;
    const row = P[(o.sex === "F" ? "F" : "M") + (o.tob ? "1" : "0")]?.[o.age - P.ages[0]]; if (!row) return null;
    const pts = []; row.forEach((v, i) => { if (v != null) pts.push([FACES[i], v]); });
    if (pts.length < 2) return null;
    const f = o.face, last = pts[pts.length - 1];
    if (f > last[0]) return null;
    let i = pts.findIndex((p) => f <= p[0]); if (i < 1) i = 1;
    const [x0, y0] = pts[i - 1], [x1, y1] = pts[i];
    return Math.max(0.01, Math.round((y0 + ((f - x0) * (y1 - y0)) / (x1 - x0)) * 100) / 100);
  }
  // the highest face this plan sells at this age, or 0
  function maxFace(id, o) {
    const row = G.products[id]?.[(o.sex === "F" ? "F" : "M") + (o.tob ? "1" : "0")]?.[o.age - G.products[id].ages[0]]; if (!row) return 0;
    let m = 0; row.forEach((v, i) => { if (v != null) m = FACES[i]; }); return m;
  }
  G.price = price; G.maxFace = maxFace;
  window.HP_GRID = G;
})();
""" % json.dumps({"asOf": "Oct 2026", "source": "Insurance Toolkits live grid (bank draft, clean health, 4,000 scenarios)", "faces": FACES, "products": out}, separators=(",", ":"))
open("public/hp-grid.js", "w").write(js)
print({k: v["ages"] for k, v in out.items()}, len(js))

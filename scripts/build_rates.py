"""Build exact carrier rate tables for the quoter from data/*.json into the generated block of public/hp-rates.js.
   Mutual of Omaha Living Promise (data/moo-living-promise.json) and American Amicable Senior Choice (data/amam-senior-choice.json).
   Monthly bank draft = (annual rate per $1,000 x units + annual policy fee) x monthly factor.
Usage: python3 -I scripts/build_rates.py"""
import json, re

def rows(table, a0, a1):
    return [table[str(a)] for a in range(a0, a1 + 1)]

def interp(points, x):
    xs = sorted(points)
    if x <= xs[0]: return points[xs[0]]
    if x >= xs[-1]: return points[xs[-1]]
    i = next(j for j in range(1, len(xs)) if x <= xs[j])
    t = (x - xs[i - 1]) / (xs[i] - xs[i - 1])
    return points[xs[i - 1]] + t * (points[xs[i]] - points[xs[i - 1]])

# ---------- Mutual of Omaha Living Promise ----------
M = json.load(open("data/moo-living-promise.json"))
fee, mf = M["fee"], M["monthly"]
rate = lambda monthly: (monthly / mf - fee) / 10  # $10,000 monthly sample -> annual rate per $1,000
# Graded has no printed table: graded/level rate ratio by age and sex from the 2026 published $10,000 samples
ratio = {s: {a: rate(M["samples2026"]["graded"][s][a]) / rate(M["samples2026"]["level"][s][a]) for a in M["samples2026"]["level"][s]} for s in ("M", "F")}
ratio = {s: {int(a): v for a, v in r.items()} for s, r in ratio.items()}
level = rows(M["level"], 45, 85)
graded = []
for i, r in enumerate(level):
    a = 45 + i
    rm, rf = interp(ratio["M"], a), interp(ratio["F"], a)
    graded.append([round(r[0] * rm, 2), round(r[1] * rm, 2), round(r[2] * rf, 2), round(r[3] * rf, 2)])  # MN MT FN FT
moLp = {"carrier": M["carrier"], "plan": M["plan"], "asOf": "rate chart UC8167", "source": M["source"], "checked": M["checked"],
        "fee": fee, "monthly": mf, "minAge": 45, "maxAge": 85, "faceMin": M["faceMin"], "faceMax": M["faceMax"], "cols": M["cols"],
        "level": level, "graded": graded, "gradedExact": False,
        "gradedNote": "Graded rates = level rates x the graded/level ratio in 2026 published samples (no graded table printed)"}

# ---------- American Amicable Senior Choice ----------
A = json.load(open("data/amam-senior-choice.json"))
aaSc = {"carrier": A["carrier"], "plan": A["plan"], "asOf": "checked Feb 2026", "source": A["source"], "checked": A["checked"],
        "fee": A["fee"], "monthly": A["monthly"], "minAge": 50, "maxAge": 85, "cols": A["cols"],
        "level": rows(A["immediate"], 50, 85), "graded": rows(A["graded"], 50, 85), "rop": rows(A["rop"], 50, 85), "gradedExact": True}

block = ("/* BEGIN generated by scripts/build_rates.py from data/moo-living-promise.json and data/amam-senior-choice.json. Do not edit by hand. */\n"
         "window.HP_RATES = Object.assign(window.HP_RATES || {}, " + json.dumps({"moLp": moLp, "aaSc": aaSc}) + ");\n"
         "/* END generated */\n")
src = open("public/hp-rates.js").read()
if "/* BEGIN generated by scripts/build_rates.py" in src:
    src = re.sub(r"/\* BEGIN generated by scripts/build_rates\.py.*?/\* END generated \*/\n", lambda m: block, src, flags=re.S)
else:
    src = src.rstrip("\n") + "\n" + block
open("public/hp-rates.js", "w").write(src)
print("Mutual of Omaha graded/level ratios:", {s: {a: round(v, 3) for a, v in r.items()} for s, r in ratio.items()})
print("wrote moLp (45-85) and aaSc (50-85) into public/hp-rates.js")
